#!/bin/sh
# Render the accounts from the environment (.env), then run Asterisk in the
# foreground.  Everything that is not an account lives in conf/ unchanged.
set -eu

die() { echo "entrypoint: $*" >&2; exit 1; }

: "${SERVER_IP:?set SERVER_IP in .env}"
: "${LOCAL_NET:?set LOCAL_NET in .env}"
: "${GATEWAY_IP:?set GATEWAY_IP in .env}"
: "${GATEWAY_USER:=gateway}"
: "${GATEWAY_PASSWORD:?set GATEWAY_PASSWORD in .env}"
: "${CLIENTS:?set CLIENTS in .env, e.g. CLIENTS=\"alice:secret1 bob:secret2\"}"

# Names and passwords end up inside config files: keep them to characters that
# cannot break the syntax.
safe() { printf '%s' "$1" | grep -Eq '^[A-Za-z0-9._-]+$'; }
safe "$GATEWAY_USER" || die "GATEWAY_USER may only contain letters, digits, . _ -"
safe "$GATEWAY_PASSWORD" || die "GATEWAY_PASSWORD may only contain letters, digits, . _ -"
[ ${#GATEWAY_PASSWORD} -ge 12 ] || die "GATEWAY_PASSWORD must be at least 12 characters"

endpoint() {  # name context message_context max_contacts
    cat <<EOF

[$1]
type=endpoint
context=$2
message_context=$3
identify_by=username,ip
disallow=all
allow=g722,alaw,ulaw
aors=$1
auth=$1-auth
direct_media=no
dtmf_mode=rfc4733
rtp_symmetric=yes
force_rport=yes
rewrite_contact=yes

[$1-auth]
type=auth
auth_type=userpass
username=$1
password=$5

[$1]
type=aor
max_contacts=$4
remove_existing=yes
qualify_frequency=30
EOF
}

{
    cat <<EOF
; Generated by entrypoint.sh from .env — edit .env, not this file.

[global]
type=global
user_agent=gsm2sip-asterisk

[transport-udp]
type=transport
protocol=udp
bind=$SERVER_IP:5060
local_net=$LOCAL_NET

; Some desktop clients (Linphone) insist on UDP 5060 locally and fail when it
; is taken on the same host; they can use TCP instead.
[transport-tcp]
type=transport
protocol=tcp
bind=$SERVER_IP:5060
local_net=$LOCAL_NET
EOF

    # The gateway.  Its INVITEs carry the GSM caller in From, not the account
    # name, so they are matched to the endpoint by source address and then
    # challenged like any other request.
    endpoint "$GATEWAY_USER" from-gateway sms-from-gateway 1 "$GATEWAY_PASSWORD"
    cat <<EOF

[$GATEWAY_USER-identify]
type=identify
endpoint=$GATEWAY_USER
match=$GATEWAY_IP
EOF

    names=""
    for entry in $CLIENTS; do
        name=${entry%%:*}
        pass=${entry#*:}
        [ "$name" != "$entry" ] || die "client '$entry' must be name:password"
        safe "$name" || die "client name '$name' may only contain letters, digits, . _ -"
        safe "$pass" || die "password for '$name' may only contain letters, digits, . _ -"
        [ ${#pass} -ge 12 ] || die "password for '$name' must be at least 12 characters"
        [ "$name" != "$GATEWAY_USER" ] || die "client '$name' has the gateway's name"
        endpoint "$name" from-clients sms-from-clients 5 "$pass"
        names="${names:+$names,}$name"
    done
} > /etc/asterisk/pjsip.conf
chmod 600 /etc/asterisk/pjsip.conf

cat > /etc/asterisk/extensions_globals.conf <<EOF
; Generated by entrypoint.sh from .env.
[globals]
SERVER_IP=$SERVER_IP
GATEWAY=$GATEWAY_USER
CLIENTS=$names
EOF

echo "entrypoint: gateway '$GATEWAY_USER' from $GATEWAY_IP, clients: $names"
exec asterisk -f -vvv -T
